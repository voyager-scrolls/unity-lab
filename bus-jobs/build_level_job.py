def load(path, label):
    with io.open(path, "r", encoding="utf-8-sig") as f:
        text = f.read()
    if "\\\\" in text:
        sys.exit("FATAL: backslash found in %s (zero-backslash rule)" % label)
    if not text.endswith("\n"):
        text += "\n"
    return text

